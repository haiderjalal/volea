// Concatenates the migrations, seed and self-check into supabase/setup.sql —
// one file to paste into the Supabase SQL Editor. Keeps setup.sql from drifting
// away from the migrations, which are the source of truth.
//
//   npm run db:bundle

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "supabase");
const read = (p) => readFileSync(join(root, p), "utf8").trimEnd();

// Globbed, not listed: a hardcoded list is how a new migration silently fails
// to reach setup.sql.
const migrations = readdirSync(join(root, "migrations"))
  .filter((f) => f.endsWith(".sql"))
  .sort();

const HEADER = `-- ============================================================================
--  Volea — one-shot database setup
--  GENERATED by scripts/bundle-sql.mjs — edit supabase/migrations/* instead.
--
--  Paste this whole file into the Supabase SQL Editor and run it once.
--  The editor runs it as a single transaction, so it either fully succeeds or
--  leaves the database untouched. The final block drives four players through
--  queue -> match -> court -> result -> rating and raises if anything is wrong,
--  so a clean run is a verified install.
-- ============================================================================

do $guard$
begin
  if exists (
    select 1 from pg_tables where schemaname = 'public' and tablename = 'matches'
  ) then
    raise exception
      'Volea is already installed here. Drop the existing tables first if you meant to reinstall.';
  end if;
end $guard$;
`;

const SECTIONS = [
  ...migrations.map((f) => [f.replace(/^\d+_|\.sql$/g, "").replace(/_/g, " "), `migrations/${f}`]),
  ["demo clubs", "seed.sql"],
  ["self-check", "tests/matchmaking.test.sql"],
];

const body = SECTIONS.map(
  ([title, file]) =>
    `\n-- ============================ ${title} ============================\n\n${read(file)}\n`,
).join("");

const out = `${HEADER}${body}`;
writeFileSync(join(root, "setup.sql"), out, "utf8");

console.log(
  `supabase/setup.sql — ${out.split("\n").length} lines from ${SECTIONS.length} sources`,
);
